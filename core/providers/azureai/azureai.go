// DefaultAzureAIApiVersion is the default API version used for Azure AI Foundry
// (Models API) and Azure OpenAI-compatible endpoints.
const DefaultAzureAIApiVersion = "2024-05-01-preview"

// AzureAIProvider implements the Provider interface for Azure AI Foundry's API.
type AzureAIProvider struct {
	logger              schemas.Logger        // Logger for provider operations
	client              *fasthttp.Client      // HTTP client for unary API requests (ReadTimeout bounds overall response)
	streamingClient     *fasthttp.Client      // HTTP client for streaming API requests (no ReadTimeout; idle governed by NewIdleTimeoutReader)
	networkConfig       schemas.NetworkConfig // Network configuration including extra headers
	sendBackRawRequest  bool                  // Whether to include raw request in BifrostResponse
	sendBackRawResponse bool                  // Whether to include raw response in BifrostResponse
}

// NewAzureAIProvider creates a new Azure AI Foundry provider instance.
// It initializes the HTTP client with the provided configuration and sets up response pools.
// The client is configured with timeouts, concurrency limits, and optional proxy settings.
func NewAzureAIProvider(config *schemas.ProviderConfig, logger schemas.Logger) (*AzureAIProvider, error) {
	config.CheckAndSetDefaults()

	requestTimeout := time.Second * time.Duration(config.NetworkConfig.DefaultRequestTimeoutInSeconds)
	client := &fasthttp.Client{
		ReadTimeout:         requestTimeout,
		WriteTimeout:        requestTimeout,
		MaxConnsPerHost:     config.NetworkConfig.MaxConnsPerHost,
		MaxIdleConnDuration: time.Second * time.Duration(config.NetworkConfig.KeepAliveTimeoutInSeconds),
		MaxConnWaitTimeout:  requestTimeout,
		MaxConnDuration:     time.Second * time.Duration(schemas.DefaultMaxConnDurationInSeconds),
		ConnPoolStrategy:    fasthttp.FIFO,
	}

	// Configure proxy and retry policy
	client = providerUtils.ConfigureProxy(client, config.ProxyConfig, logger)
	client = providerUtils.ConfigureDialer(client, config.NetworkConfig.AllowPrivateNetwork)
	client = providerUtils.ConfigureTLS(client, config.NetworkConfig, logger)
	streamingClient := providerUtils.BuildStreamingClient(client)
	config.NetworkConfig.BaseURL = strings.TrimRight(config.NetworkConfig.BaseURL, "/")

	return &AzureAIProvider{
		logger:              logger,
		client:              client,
		streamingClient:     streamingClient,
		networkConfig:       config.NetworkConfig,
		sendBackRawRequest:  config.SendBackRawRequest,
		sendBackRawResponse: config.SendBackRawResponse,
	}, nil
}

// resolveAzureAIEndpoint returns the per-key endpoint if configured, otherwise
// the provider-level BaseURL. An empty result means the provider is misconfigured.
func (provider *AzureAIProvider) resolveAzureAIEndpoint(key schemas.Key) string {
	if key.AzureAIKeyConfig != nil {
		if v := key.AzureAIKeyConfig.Endpoint.GetValue(); v != "" {
			return strings.TrimRight(v, "/")
		}
	}
	return provider.networkConfig.BaseURL
}

// resolveAzureAIURL builds the full request URL (endpoint + path + api-version).
func (provider *AzureAIProvider) resolveAzureAIURL(ctx *schemas.BifrostContext, key schemas.Key, path string) (string, *schemas.BifrostError) {
	endpoint := provider.resolveAzureAIEndpoint(key)
	if endpoint == "" {
		return "", providerUtils.NewConfigurationError("endpoint not set for azure_ai provider (set base_url or azure_ai_key_config.endpoint)")
	}
	fullURL := endpoint + providerUtils.GetPathFromContext(ctx, path)
	if !strings.Contains(fullURL, "?") {
		fullURL += "?api-version=" + DefaultAzureAIApiVersion
	}
	return fullURL, nil
}

// azureAIAPIKeyHeader returns the api-key auth header used by Azure AI Foundry
// serverless and Azure OpenAI-compatible endpoints.
func (provider *AzureAIProvider) azureAIAPIKeyHeader(key schemas.Key) map[string]string {
	if v := key.Value.GetValue(); v != "" {
		return map[string]string{"api-key": v}
	}
	return nil
}

// GetProviderKey returns the provider identifier for Azure AI Foundry.
func (provider *AzureAIProvider) GetProviderKey() schemas.ModelProvider {
	return schemas.AzureAI
}

// ListModels performs a list models request to Azure AI Foundry's API.
func (provider *AzureAIProvider) ListModels(ctx *schemas.BifrostContext, keys []schemas.Key, request *schemas.BifrostListModelsRequest) (*schemas.BifrostListModelsResponse, *schemas.BifrostError) {
	endpoint := provider.networkConfig.BaseURL
	if endpoint == "" && len(keys) > 0 {
		endpoint = provider.resolveAzureAIEndpoint(keys[0])
	}
	if endpoint == "" {
		return nil, providerUtils.NewConfigurationError("endpoint not set for azure_ai provider (set base_url or azure_ai_key_config.endpoint)")
	}
	listModelsURL := endpoint + providerUtils.GetPathFromContext(ctx, "/models")
	if !strings.Contains(listModelsURL, "?") {
		listModelsURL += "?api-version=" + DefaultAzureAIApiVersion
	}
	return openai.HandleOpenAIListModelsRequest(
		ctx,
		provider.client,
		request,
		listModelsURL,
		keys,
		provider.networkConfig.ExtraHeaders,
		provider.GetProviderKey(),
		providerUtils.ShouldSendBackRawRequest(ctx, provider.sendBackRawRequest),
		providerUtils.ShouldSendBackRawResponse(ctx, provider.sendBackRawResponse),
	)
}

// TextCompletion performs a text completion request to Azure AI Foundry's API.
// It formats the request, sends it to Azure AI Foundry, and processes the response.
// Returns a BifrostResponse containing the completion results or an error if the request fails.
func (provider *AzureAIProvider) TextCompletion(ctx *schemas.BifrostContext, key schemas.Key, request *schemas.BifrostTextCompletionRequest) (*schemas.BifrostTextCompletionResponse, *schemas.BifrostError) {
	url, bifrostErr := provider.resolveAzureAIURL(ctx, key, "/completions")
	if bifrostErr != nil {
		return nil, bifrostErr
	}
	return openai.HandleOpenAITextCompletionRequest(
		ctx,
		provider.client,
		url,
		request,
		provider.azureAIAPIKeyHeader(key),
		provider.networkConfig.ExtraHeaders,
		provider.GetProviderKey(),
		providerUtils.ShouldSendBackRawRequest(ctx, provider.sendBackRawRequest),
		providerUtils.ShouldSendBackRawResponse(ctx, provider.sendBackRawResponse),
		nil,
		nil,
		provider.logger,
	)
}

// TextCompletionStream performs a streaming text completion request to Azure AI Foundry's API.
// It formats the request, sends it to Azure AI Foundry, and processes the response.
// Returns a channel of BifrostStreamChunk objects or an error if the request fails.
